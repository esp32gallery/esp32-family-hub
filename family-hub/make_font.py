#!/usr/bin/env python3
"""Generate the small Chinese bitmap font used by the 480 px UI."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import re

TEXT = (
    "骰子语音信箱爸爸妈妈我自己按住说话松开发送录中正在成功失败"
    "设置亮度量配网连接重新服务器返回主页最近消息选择联系人"
    "暂无点播放停止太短秒刷新外离线已发收听轻触打开保存取消"
    "录制上传网络未可用拖动调整保存好请检查开始结束"
)
SOURCE = Path(__file__).with_name("family-hub.ino").read_text()
LITERALS = "".join(re.findall(r'"([^"\\]*(?:\\.[^"\\]*)*)"', SOURCE))
CHARS = "".join(sorted({c for c in TEXT + LITERALS if "\u4e00" <= c <= "\u9fff"}))
FONT = "/Users/liu1/Library/Fonts/NotoSansCJK.ttc"
SIZE = 24
font = ImageFont.truetype(FONT, 21)
out = Path(__file__).with_name("zh_font.h")
lines = [
    "// Generated by make_font.py from Noto Sans CJK; 24x24 monochrome glyphs.",
    "#pragma once", "#include <Arduino.h>",
    f"static const uint32_t ZH_CODES[{len(CHARS)}] = {{",
    ", ".join(f"0x{ord(c):04X}" for c in CHARS) + "};",
    f"static const uint8_t ZH_BITS[{len(CHARS)}][72] PROGMEM = {{",
]
for c in CHARS:
    im = Image.new("L", (SIZE, SIZE), 0)
    d = ImageDraw.Draw(im)
    box = d.textbbox((0, 0), c, font=font)
    d.text(((SIZE - (box[2] - box[0])) // 2 - box[0],
            (SIZE - (box[3] - box[1])) // 2 - box[1]), c, font=font, fill=255)
    values = []
    for y in range(SIZE):
        for x0 in range(0, SIZE, 8):
            values.append(sum((1 << (7 - bit)) for bit in range(8)
                              if im.getpixel((x0 + bit, y)) >= 100))
    lines.append("  {" + ",".join(f"0x{v:02X}" for v in values) + "}, // " + c)
lines.append("};")
out.write_text("\n".join(lines) + "\n")
print(f"{len(CHARS)} glyphs, {len(CHARS)*72} bitmap bytes -> {out}")
